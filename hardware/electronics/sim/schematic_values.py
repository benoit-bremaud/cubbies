"""Write schematic.lib: the resistor and capacitor values captured on the KiCad schematic.

Simulations are fed from the schematic (V-SEA method): a value changed on the sheet reaches the
benches without being copied by hand. This exports the SPICE netlist of
../cubbies-v1.kicad_sch with kicad-cli and writes, for every R and C, the nominal value both as
`.param <ref>=<value>` (for netlist expressions) and `.csparam` (a vector for .control blocks).
Values are written as plain numbers: SPICE reads `M` as milli. Parts excluded from simulation
(modules, diodes, MOSFET, buzzer) are modelled by each bench itself.

    python3 schematic_values.py   (from this folder; needs kicad-cli 9)
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SCH = HERE.parent / "cubbies-v1.kicad_sch"
SI = {"p": 1e-12, "n": 1e-9, "u": 1e-6, "µ": 1e-6, "m": 1e-3, "k": 1e3, "M": 1e6}


def si_value(text: str) -> float:
    """'10k' -> 10000, '1uF X7R' -> 1e-06, '4k7' -> 4700, '82' -> 82; the first word counts."""
    m = re.fullmatch(r"(\d+(?:\.\d+)?)([pnuµmkM]?)(\d*)[FΩ]?", text.split()[0])
    if not m:
        sys.exit(f"unreadable value: {text!r}")
    whole, prefix, decimals = m.groups()
    return float(whole + ("." + decimals if decimals else "")) * SI.get(prefix, 1.0)


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        cir = pathlib.Path(tmp) / "cubbies-v1.cir"
        subprocess.run(
            [
                "kicad-cli",
                "sch",
                "export",
                "netlist",
                "--format",
                "spice",
                "-o",
                str(cir),
                str(SCH),
            ],
            check=True,
            capture_output=True,
        )
        lines = cir.read_text().splitlines()
    out = [
        "* schematic.lib -- generated by schematic_values.py from ../cubbies-v1.kicad_sch: do not edit"
    ]
    for line in lines:
        f = line.split(None, 3)
        if len(f) == 4 and f[0][0] in "RC":
            ref, value = f[0].lower(), si_value(f[3])
            out += [f".param {ref}={value:g}", f".csparam {ref}={value:g}"]
    if len(out) == 1:
        sys.exit("no R or C found in the schematic netlist")
    (HERE / "schematic.lib").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
